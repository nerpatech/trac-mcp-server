"""Version checking utilities for detecting stale MCP server binaries."""

import re
import sys
from collections.abc import Callable
from pathlib import Path

#: What a stamped sha looks like: 40 hex, ``-dirty`` when the tree had
#: changes. Matches what ``setup.py`` writes.
_STAMP = re.compile(r"[0-9a-f]{40}(-dirty)?\Z")

#: The data file build.sh bundles into a PyInstaller binary.
FROZEN_SHA_FILE = "trac_mcp_server_RELEASE_SHA"


def release_sha() -> str | None:
    """The commit this build was made from, or None.

    ``setup.py`` writes ``trac_mcp_server/_release.py`` into the build
    directory when it builds from a source checkout (Trac
    /trac_mcp_server #170); a checkout run in place, an editable install
    and a build from an sdist have no such module. A trailing ``-dirty``
    means a tracked file differed from the commit at build time.

    A PyInstaller binary never runs ``setup.py``'s build step, so it has
    no ``_release`` module either. ``build.sh`` bundles the sha as the
    data file ``trac_mcp_server_RELEASE_SHA`` (``--add-data``), which
    lands in ``sys._MEIPASS``; when the import fails in a frozen process
    that file is read instead (Trac /trac_mcp_server #230). Its content
    must be 40 hex, optionally ``-dirty``; anything else, or an
    unreadable or undecodable file, is None. The ``_release`` value is
    held to the same shape.
    """
    try:
        from ._release import (  # pyright: ignore[reportMissingImports]  # generated by build.sh
            RELEASE_SHA,
        )
    except ImportError:
        return _frozen_release_sha()
    if isinstance(RELEASE_SHA, str) and _STAMP.match(RELEASE_SHA):
        return RELEASE_SHA
    return None


def _frozen_release_sha() -> str | None:
    """The sha build.sh bundled into a PyInstaller binary, or None."""
    if not getattr(sys, "frozen", False):
        return None
    # PyInstaller sets sys._MEIPASS at runtime; no stub declares it.
    meipass = getattr(sys, "_MEIPASS", None)
    if meipass is None:
        return None
    try:
        text = (Path(meipass) / FROZEN_SHA_FILE).read_text(
            encoding="ascii"
        )
    except (OSError, ValueError):
        return None
    sha = text.strip()
    return sha if _STAMP.match(sha) else None


def format_server_version(version: str, sha: str | None) -> str:
    """``serverInfo.version``: the package version, plus a PEP
    440-style local segment naming the commit when it is known.

    ``2.2.0`` + ``<sha>`` gives ``2.2.0+g<first 12 of sha>``; a dirty
    sha gives ``2.2.0+g<12>.dirty``.
    """
    if not sha:
        return version
    dirty = sha.endswith("-dirty")
    short = sha.removesuffix("-dirty")[:12]
    return f"{version}+g{short}" + (".dirty" if dirty else "")


def format_cli_version(version: str, sha: str | None) -> str:
    """``--version`` of the command-line tools: the server's form when
    the commit is known, else the version with an explicit
    ``(commit unknown)`` rather than a bare number that reads as a
    complete answer (Trac /trac_mcp_server #230)."""
    if sha:
        return format_server_version(version, sha)
    return f"{version} (commit unknown)"


def cli_version() -> str:
    """The string a command-line ``--version`` prints after its name:
    the package version and the build commit (Trac /trac_mcp_server
    #230). Looks ``release_sha`` up at call time."""
    from . import __version__

    return format_cli_version(__version__, release_sha())


#: The distribution name; what ``[project].name`` and the installed
#: metadata call this package.
DIST_NAME = "trac-mcp-server"


def _installed_version() -> str | None:
    """The installed distribution's version, or None when there is no
    metadata for it (a PyInstaller binary, a bare source run)."""
    from importlib.metadata import PackageNotFoundError, version

    try:
        return version(DIST_NAME)
    except PackageNotFoundError:
        return None


def _compare_versions(
    runtime_version: str,
    manifest_path: Path,
    dist_version: Callable[[], str | None],
) -> tuple[bool, str]:
    """``check_version_consistency`` with its inputs passed in, so tests
    can drive each source with real files and a stand-in lookup."""
    if manifest_path.exists():
        # tomllib is stdlib from 3.11; tomli is the fallback for 3.10
        try:
            import tomllib  # type: ignore[import-not-found]
        except ImportError:
            try:
                import tomli as tomllib  # type: ignore[no-redef]
            except ImportError:
                return (
                    False,
                    "tomllib/tomli not available for version checking",
                )
        try:
            with open(manifest_path, "rb") as f:
                project = tomllib.load(f).get("project", {})
            name = project.get("name")
            source_version = project.get("version", "unknown")
        except Exception as e:
            return (
                False,
                f"Failed to read version from pyproject.toml: {e}",
            )
        # A manifest for some other project (or none that names one) is
        # not this package's source tree: look at the installed metadata.
        if name == DIST_NAME:
            if runtime_version != source_version:
                return False, (
                    f"Version mismatch detected! "
                    f"Runtime: {runtime_version}, Source: {source_version}. "
                    f"Binary is stale - rebuild with: pyinstaller trac-mcp-server.spec"
                )
            return True, f"Version verified: {runtime_version}"

    installed = dist_version()
    if installed is None:
        return True, (
            f"Version {runtime_version}: no source manifest or package "
            f"metadata to compare against"
        )
    if installed != runtime_version:
        return False, (
            f"Version mismatch detected! "
            f"Runtime: {runtime_version}, Installed metadata: {installed}. "
            f"The installed package metadata disagrees with the code - "
            f"reinstall the package"
        )
    return (
        True,
        f"Version verified: {runtime_version} (installed package metadata)",
    )


def check_version_consistency() -> tuple[bool, str]:
    """Check that the running code's ``__version__`` matches the version
    its install claims (Trac /trac_mcp_server #244).

    Returns:
        Tuple of (is_consistent, message) where:
        - is_consistent: True if versions match, or if there is nothing
          to compare against; False on a mismatch or a read failure
        - message: Descriptive message about version status

    The version is compared against the first of three sources that
    exists:

    1. The source manifest, ``pyproject.toml`` three levels above this
       file, when it names this project (``[project].name`` is
       ``trac-mcp-server``). That is a source checkout or an editable
       install, and it goes first because an editable install's dist
       metadata goes stale (it keeps the version from install time)
       while the manifest is the live source. A mismatch means a stale
       PyInstaller binary; a manifest that cannot be read is a failure.
    2. The installed distribution's metadata
       (``importlib.metadata``), for any other install: a wheel in a
       venv or site-packages, where the path above names ``lib/pythonX.Y``
       and there is no manifest. A mismatch means the package should be
       reinstalled.
    3. Neither (a PyInstaller binary with no bundled metadata): there is
       nothing to compare, which is consistent, so the caller logs it at
       info and not as a warning.
    """
    try:
        from . import __version__ as runtime_version
    except ImportError:
        return False, "Cannot import __version__ from trac_mcp_server"

    return _compare_versions(
        runtime_version,
        Path(__file__).parent.parent.parent / "pyproject.toml",
        _installed_version,
    )
