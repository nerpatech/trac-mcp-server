"""Code-fence languages Trac has no processor for (Trac /trac_mcp_server #240).

A Markdown fence ``` ```pf ``` used to become ``{{{#!pf}}}``. Trac has no
``pf`` processor, so the block rendered as an error box, and a fence that
names one of Trac's *own* processors (``div``, ``span``, ``comment``,
``default``, ``html``) ran that processor instead of showing the code.

The rule: a name is written as ``#!NAME`` only when Trac highlights it (the
allow-list ``TRAC_CODE_LANGUAGES``, generated by
``scripts/probe_fence_languages.py``). Anything else is written as
``#!text lang=NAME`` (a plain block, the name kept for a reader) and
reported by ``convert_with_warnings``.
"""

import re

import pytest

from trac_mcp_server.converters.common import _MARKDOWN_TO_TRACWIKI_MAP
from trac_mcp_server.converters.markdown_to_tracwiki import (
    convert_with_warnings,
    markdown_to_tracwiki,
)


def _fence(info: str, body: str = "x") -> str:
    return f"```{info}\n{body}\n```\n"


@pytest.mark.parametrize("name", ["pf", "graphql", "mermaid"])
def test_a_language_trac_cannot_highlight_becomes_text_lang(name):
    assert markdown_to_tracwiki(_fence(name)) == (
        f"{{{{{{#!text lang={name}\nx\n}}}}}}"
    )


def test_an_html_fence_shows_the_code_instead_of_rendering_it():
    assert markdown_to_tracwiki(_fence("html", "<p>x</p>")) == (
        "{{{#!text/html\n<p>x</p>\n}}}"
    )


@pytest.mark.parametrize("name", ["div", "span", "comment", "default"])
def test_a_trac_processor_name_no_longer_runs_the_processor(name):
    assert markdown_to_tracwiki(_fence(name)) == (
        f"{{{{{{#!text lang={name}\nx\n}}}}}}"
    )


def test_a_highlighted_language_is_written_as_typed():
    assert markdown_to_tracwiki(_fence("python")) == (
        "{{{#!python\nx\n}}}"
    )


@pytest.mark.parametrize(
    ("info", "processor"),
    [("bash", "sh"), ("js", "javascript"), ("plaintext", "text")],
)
def test_a_mapped_name_is_written_as_its_trac_name(info, processor):
    assert markdown_to_tracwiki(_fence(info)) == (
        f"{{{{{{#!{processor}\nx\n}}}}}}"
    )


def test_the_allow_list_is_compared_lowercased_and_emitted_lowercased():
    """Pinned: `PYTHON` is in the list once lowercased, so it is not
    downgraded, and is written as `python`, the form measured on Trac."""
    assert markdown_to_tracwiki(_fence("PYTHON")) == (
        "{{{#!python\nx\n}}}"
    )


def test_extra_words_in_the_info_string_are_dropped():
    assert markdown_to_tracwiki(_fence("python title=x")) == (
        "{{{#!python\nx\n}}}"
    )


def test_a_name_that_could_break_the_opener_gets_no_lang_attribute():
    out = markdown_to_tracwiki(_fence("p}}}f", "keep this"))
    assert out == "{{{#!text\nkeep this\n}}}"


def test_every_mapped_name_is_in_the_allow_list():
    from trac_mcp_server.converters.fence_languages import (
        TRAC_CODE_LANGUAGES,
    )

    for src, mapped in _MARKDOWN_TO_TRACWIKI_MAP.items():
        assert mapped.lower() in TRAC_CODE_LANGUAGES, (src, mapped)


def test_the_allow_list_has_no_trac_processor_names():
    from trac_mcp_server.converters.fence_languages import (
        TRAC_CODE_LANGUAGES,
    )

    for name in ("div", "span", "comment", "default", "html", "pf"):
        assert name not in TRAC_CODE_LANGUAGES, name
    for name in ("python", "text", "text/html", "sh", "c++"):
        assert name in TRAC_CODE_LANGUAGES, name


def _fence_warnings(md: str) -> list[str]:
    return [
        w
        for w in convert_with_warnings(md).warnings
        if w.startswith("Code fence language")
    ]


def test_one_warning_per_distinct_downgraded_name_in_order():
    md = _fence("pf") + "\n" + _fence("graphql") + "\n" + _fence("pf")
    assert _fence_warnings(md) == [
        "Code fence language 'pf' is not a language Trac highlights; "
        "written as a plain code block ({{{#!text lang=pf}}}).",
        "Code fence language 'graphql' is not a language Trac "
        "highlights; written as a plain code block "
        "({{{#!text lang=graphql}}}).",
    ]


def test_the_warning_for_a_rejected_name_names_the_bare_form():
    assert convert_with_warnings(_fence("p}}}f")).warnings == [
        "Code fence language 'p}}}f' is not a language Trac "
        "highlights; written as a plain code block ({{{#!text}}})."
    ]


# -- Trac's processor-name grammar: [\w+-][\w+/-]* --------------------------


@pytest.mark.parametrize(
    ("info", "opener"),
    [
        ("c#", "#!csharp"),
        ("f#", "#!fsharp"),
        ("python{1,3}", "#!python"),
        ("python:file.py", "#!python"),
        ("js{2}", "#!javascript"),
        ("PYTHON{1}", "#!python"),
    ],
)
def test_an_info_string_suffix_is_dropped_and_the_name_mapped(
    info, opener
):
    assert markdown_to_tracwiki(_fence(info)) == (
        f"{{{{{{{opener}\nx\n}}}}}}"
    )
    assert _fence_warnings(_fence(info)) == []


@pytest.mark.parametrize("info", ["pf{1}", "pf:file", "{x", "div{1}"])
def test_a_suffixed_name_that_is_not_highlighted_falls_back(info):
    assert markdown_to_tracwiki(_fence(info)) == "{{{#!text\nx\n}}}"


def test_a_prefix_that_trac_would_run_as_c_is_written_as_c():
    # Trac reads `{{{#!c#x` as processor `c`, so that is what we emit.
    assert markdown_to_tracwiki(_fence("c#x")) == "{{{#!c\nx\n}}}"


def test_the_grammar_constant_is_trac_s_processor_name_grammar():
    from trac_mcp_server.converters.common import PROCESSOR_NAME_RE

    assert PROCESSOR_NAME_RE.pattern == r"[\w+-][\w+/-]*"
    assert PROCESSOR_NAME_RE.fullmatch("text/html")
    assert not PROCESSOR_NAME_RE.fullmatch("c#")


def test_the_allow_list_holds_only_names_of_the_grammar():
    from trac_mcp_server.converters.common import PROCESSOR_NAME_RE
    from trac_mcp_server.converters.fence_languages import (
        TRAC_CODE_LANGUAGES,
    )

    assert "csharp" in TRAC_CODE_LANGUAGES
    assert "fsharp" in TRAC_CODE_LANGUAGES
    for name in TRAC_CODE_LANGUAGES:
        assert PROCESSOR_NAME_RE.fullmatch(name), name


# -- Placeholders in the info string never reach the warning ------------------


def test_a_bracket_macro_info_string_is_restored_in_the_warning():
    result = convert_with_warnings("```[[x]]\ncode\n```\n")
    assert result.text == "{{{#!text\ncode\n}}}"
    assert result.warnings == [
        "Code fence language '[[x]]' is not a language Trac "
        "highlights; written as a plain code block ({{{#!text}}})."
    ]


def test_a_code_span_info_string_is_restored_in_the_warning():
    result = convert_with_warnings("~~~`x`\ncode\n~~~\n")
    assert result.text == "{{{#!text\ncode\n}}}"
    assert result.warnings == [
        "Code fence language '`x`' is not a language Trac "
        "highlights; written as a plain code block ({{{#!text}}})."
    ]


def test_known_languages_give_no_fence_warning():
    md = _fence("python") + "\n" + _fence("bash") + "\n" + _fence("")
    warnings = convert_with_warnings(md).warnings
    assert not [w for w in warnings if w.startswith("Code fence")]


def test_the_public_function_is_exported():
    from trac_mcp_server.converters import fence_processor

    assert fence_processor("pf") == ("#!text lang=pf", "pf")
    assert fence_processor("python") == ("#!python", None)
    assert fence_processor("p}}}f") == ("#!text", "p}}}f")


# -- Live: Trac's own renderer on /trac_test ---------------------------------


@pytest.mark.live
def test_live_downgraded_fences_render_as_code_not_errors_or_processors():
    """Trac #240 acceptance: pf, graphql, html, div and comment fences
    each show their code inside a <pre>, no error box. Read-only
    (wiki.wikiToHtml writes nothing)."""
    import xmlrpc.client

    from tests.live_helpers import TEST_INSTANCE, trac_test_registry
    from trac_mcp_server.config_bootstrap import bootstrap_config
    from trac_mcp_server.core.client import TracClient

    config, _ = bootstrap_config()
    client = TracClient(
        trac_test_registry(config).resolve(TEST_INSTANCE)
    )

    bodies = {
        "pf": "pf_marker_one",
        "graphql": "graphql_marker_two",
        "html": "<p>html_marker_three</p>",
        "div": "div_marker_four",
        "comment": "comment_marker_five",
        "python": "python_marker_six = 1",
    }
    md = "\n".join(_fence(n, b) for n, b in bodies.items())
    wiki = markdown_to_tracwiki(md)
    html = xmlrpc.client.loads(
        client._rpc_call("wiki", "wikiToHtml", wiki).content
    )[0][0]

    assert "system-message" not in html, html
    pres = re.findall(r"<pre.*?</pre>", html, flags=re.DOTALL)
    assert len(pres) == len(bodies), html
    for name, body in bodies.items():
        # a highlighted body is split into spans, so match the marker word
        marker = re.search(r"\w+_marker_\w+", body)
        assert marker is not None
        assert any(marker.group(0) in p for p in pres), (name, html)
