#!/usr/bin/env python3
"""Regenerate ``converters/fence_languages.py`` (Trac /trac_mcp_server #240).

A Markdown fence whose language Trac has no processor for becomes an error
box, and a fence naming one of Trac's own processors (html, div, span,
comment, default) runs that processor instead of showing code. The
converter therefore writes ``{{{#!NAME}}}`` only for names Trac
highlights, and this script finds them.

It takes every alias of every lexer in the locally installed Pygments
(``pygments.lexers.get_all_lexers()``) plus ``text/plain``,
``text/html`` and ``svg`` (a Trac MIME keyword, not a Pygments alias),
renders ``{{{#!NAME`` / ``x = 1`` / ``}}}`` through the Trac instance's
``wiki.wikiToHtml``, and keeps a name only when the HTML holds
``class="wiki-code"`` and no ``system-message``. That criterion also drops
the names Trac runs as processors, which render without ``wiki-code``.

RERUN IT after a Trac upgrade or a Pygments upgrade on the Trac host (the
set of names Trac highlights is whatever Pygments the host has), and
commit the regenerated module. The Pygments used for the *enumeration* is
the local one, so a name only the host's Pygments knows is not probed:
run it from an environment whose Pygments is not older than the host's.

Render-only: ``wiki.wikiToHtml`` writes nothing. Credentials come from
``.env`` in the current directory (``TRAC_URL``, ``TRAC_USERNAME``,
``TRAC_PASSWORD``), as for the server.

Usage:

    python scripts/probe_fence_languages.py [--instance /trac_mcp_server]
        [--output src/trac_mcp_server/converters/fence_languages.py]

then ``ruff format`` the generated module.
"""

import argparse
import datetime
import subprocess
import sys
import xmlrpc.client
from collections.abc import Callable
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

DEFAULT_OUTPUT = (
    Path(__file__).resolve().parent.parent
    / "src"
    / "trac_mcp_server"
    / "converters"
    / "fence_languages.py"
)

# Not Pygments aliases: Trac's own MIME names and keywords (``svg`` is a
# Trac MIME keyword, not a Pygments alias; measured accepted).
EXTRA_NAMES = ("text/plain", "text/html", "svg")


def candidate_names() -> list[str]:
    """Every Pygments lexer alias, lowercased, plus the extra names.

    A candidate that does not fully match Trac's processor-name grammar
    (``c#``, ``f#``) is dropped without probing: Trac would read only its
    leading part as the processor name (``{{{#!c#`` runs ``c``).
    """
    from pygments.lexers import get_all_lexers

    from trac_mcp_server.converters.common import PROCESSOR_NAME_RE

    names = set(EXTRA_NAMES)
    for _name, aliases, _patterns, _mimes in get_all_lexers():
        names.update(alias.lower() for alias in aliases)
    return sorted(n for n in names if PROCESSOR_NAME_RE.fullmatch(n))


def accepted(html: str) -> bool:
    return 'class="wiki-code"' in html and "system-message" not in html


def probe(names: list[str], render: Callable[[str], str]) -> list[str]:
    """The names for which ``render`` answers highlighted code."""
    return sorted(
        name
        for name in names
        if accepted(render(f"{{{{{{#!{name}\nx = 1\n}}}}}}\n"))
    )


def _trac_render(instance: str) -> Callable[[str], str]:
    from trac_mcp_server.config_bootstrap import bootstrap_config
    from trac_mcp_server.core.client import TracClient
    from trac_mcp_server.instances import InstanceRegistry

    config, _ = bootstrap_config()
    client = TracClient(InstanceRegistry(config, {}).resolve(instance))

    def render(text: str) -> str:
        reply = client._rpc_call("wiki", "wikiToHtml", text)
        return xmlrpc.client.loads(reply.content)[0][0]

    return render


def module_source(
    names: list[str], instance: str, pygments_version: str, today: str
) -> str:
    body = "".join(f"        {name!r},\n" for name in names)
    return (
        f'"""Code-fence languages Trac highlights (GENERATED, do not edit).\n'
        f"\n"
        f"Generated by scripts/probe_fence_languages.py on {today} against\n"
        f"the Trac instance {instance} (the project's own Trac host),\n"
        f"enumerating the aliases of local Pygments {pygments_version}.\n"
        f"A name is listed when Trac renders\n"
        f"``{{{{{{#!NAME}}}}}}`` as highlighted code (``wiki-code``, no\n"
        f"``system-message``), which excludes Trac's own processors (html,\n"
        f"div, span, comment, default). Rerun the script after a Trac or\n"
        f"Pygments upgrade on the host. Trac /trac_mcp_server #240.\n"
        f'"""\n'
        f"\n"
        f"TRAC_CODE_LANGUAGES: frozenset[str] = frozenset(\n"
        f"    {{\n{body}    }}\n"
        f")\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--instance", default="/trac_mcp_server")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)

    import pygments

    names = candidate_names()
    kept = probe(names, _trac_render(args.instance))
    args.output.write_text(
        module_source(
            kept,
            args.instance,
            pygments.__version__,
            datetime.date.today().isoformat(),
        )
    )
    print(f"probed {len(names)}, accepted {len(kept)}")
    print(f"wrote {args.output}")
    command = [sys.executable, "-m", "ruff", "format", str(args.output)]
    try:
        formatted = subprocess.run(command, check=False).returncode == 0
    except OSError:
        formatted = False
    if not formatted:
        print(
            f"ruff format failed: {args.output} is UNFORMATTED; install "
            "ruff in this Python environment and run it on the file "
            "before you use it.",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
